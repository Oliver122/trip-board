import { firstSentence } from './parse.mjs'

const DASH = '—'
const PRETTIER_OPTIONS = {
  parser: 'markdown',
  semi: false,
  singleQuote: true,
  trailingComma: 'all',
  endOfLine: 'lf',
}

export async function formatMarkdown(text) {
  const prettier = await import('prettier')
  return prettier.format(text, PRETTIER_OPTIONS)
}

export async function isPrettierClean(text) {
  return (await formatMarkdown(text)) === text
}

const cell = (s) =>
  String(s).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim() || DASH
const list = (a) => (a.length ? a.join(', ') : DASH)
const q = (s) => s.replace(/"/g, '#quot;')

export function isUnlocated(model, id) {
  const def = model.testDefs.get(id)
  if (def && (def.type === 'manual' || def.type === 'ci')) return false
  return model.locate(id).files.length === 0
}

export function unlocatedTests(model) {
  const ids = new Set()
  for (const r of model.rules)
    for (const t of r.tests) if (isUnlocated(model, t)) ids.add(t)
  return [...ids].sort()
}

function table(head, rows) {
  return [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n')
}

export function renderIndex(model) {
  const out = []
  out.push('Generated by `pnpm req:build` — do not edit')
  out.push('# Requirements index')

  // (1) step graph
  out.push('## Step graph')
  const g = ['flowchart LR']
  for (const s of model.steps) g.push(`    S${s.num}["${s.num} ${q(s.title)}"]`)
  for (const s of model.steps) {
    for (const d of s.depends)
      if (model.stepByNum.has(d)) g.push(`    S${d} --> S${s.num}`)
  }
  out.push('```mermaid\n' + g.join('\n') + '\n```')

  // (2) steps table
  out.push('## Steps')
  out.push(
    table(
      ['#', 'Step', 'Status', 'Core', 'Result you can check'],
      model.steps.map((s) => {
        const ids = new Set(s.coreIds)
        if (s.status !== 'integrated')
          for (const c of s.changes)
            if (/^C-[A-Z]+-\d+$/.test(c.coreId)) ids.add(c.coreId)
        return [
          s.num,
          `[${cell(s.title)}](./${s.slug})`,
          s.status === 'integrated'
            ? `integrated ${s.integratedOn}`
            : 'planned',
          list([...ids].sort()),
          cell(s.result ?? ''),
        ]
      }),
    ),
  )

  // (3) rules per area
  out.push('## Core rules')
  for (const c of model.coreFiles) {
    out.push(`### ${cell(c.title)}`)
    out.push(
      `Source: [${c.file.replace('requirements/', '')}](./${c.file.replace('requirements/', '')})`,
    )
    if (!c.rules.length) {
      out.push('_No rules yet._')
      continue
    }
    out.push(
      table(
        ['ID', 'Rule', 'Status', 'Since', 'Changed by', 'Tests', 'Located in'],
        c.rules.map((r) => {
          const files = [
            ...new Set(r.tests.flatMap((t) => model.locate(t).files)),
          ].sort()
          return [
            r.id,
            cell(firstSentence(r.rule)),
            r.status,
            r.since,
            list(r.changedBy),
            list(r.tests),
            files.length ? files.map((f) => `\`${f}\``).join(', ') : DASH,
          ]
        }),
      ),
    )
  }

  // (4) coverage
  out.push('## Coverage')
  let tr = 0
  let ta = 0
  let tx = 0
  let tn = 0
  const rows = model.coreFiles.map((c) => {
    const active = c.rules.filter((r) => r.status === 'active')
    const removed = c.rules.length - active.length
    const none = active.filter((r) => r.tests.length === 0).length
    tr += c.rules.length
    ta += active.length
    tx += removed
    tn += none
    return [c.area, c.rules.length, active.length, removed, none]
  })
  rows.push(['**Total**', tr, ta, tx, tn])
  out.push(
    table(['Area', 'Rules', 'Active', 'Removed', 'Active without tests'], rows),
  )
  const miss = unlocatedTests(model)
  out.push(`T-IDs in core rules not located (non-manual): **${miss.length}**`)
  if (miss.length) out.push(miss.map((t) => `- ${t}`).join('\n'))
  return out.join('\n\n') + '\n'
}

export async function buildIndex(model) {
  return formatMarkdown(renderIndex(model))
}
